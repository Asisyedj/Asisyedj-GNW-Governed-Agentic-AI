import fs from "node:fs";
import path from "node:path";
const file = path.resolve("docs/security/100-independent-review-subjects.md");
const text = fs.readFileSync(file, "utf8");
const ids = [...text.matchAll(/\| (IRS-\d{3}) \|/g)].map(m => m[1]);
const expected = Array.from({length:100},(_,i)=>`IRS-${String(i+1).padStart(3,"0")}`);
if (ids.length !== 100) throw new Error(`FAIL: expected 100 subjects, found ${ids.length}`);
if (new Set(ids).size !== 100) throw new Error("FAIL: duplicate subject IDs");
for (let i=0;i<100;i++) if(ids[i]!==expected[i]) throw new Error(`FAIL: missing/out-of-order subject ${expected[i]}`);
const domains = [...text.matchAll(/\| IRS-\d{3} \| ([^|]+) \|/g)].map(m=>m[1].trim());
const counts = new Map(); for(const d of domains) counts.set(d,(counts.get(d)||0)+1);
if(counts.size!==10 || [...counts.values()].some(v=>v!==10)) throw new Error(`FAIL: expected 10 domains x 10 subjects, got ${JSON.stringify(Object.fromEntries(counts))}`);
const required = ["## Required execution record for every subject","subject_id:","attack:","precondition:","expected:","actual:","side_effect:","audit_evidence:","verdict:","root_cause:","fix:","regression:","reviewer:","review_timestamp:"];
for(const token of required) if(!text.includes(token)) throw new Error(`FAIL: missing required record field ${token}`);
console.log("PASS: 100 independent review subjects present");
console.log("PASS: IDs IRS-001 through IRS-100 unique and ordered");
console.log("PASS: 10 domains x 10 subjects");
console.log("PASS: required evidence record schema present");
console.log("STATUS: matrix definition validated; subject execution evidence remains separate");
